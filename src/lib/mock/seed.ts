function hash(n: number) {
  return (n * 2654435761) >>> 0;
}

function activityCount(date: Date) {
  const key =
    date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  const r = (hash(key) % 1000) / 1000;
  const month = date.getMonth();
  const threshold = month === 7 ? 0.48 : month === 9 ? 0.38 : month === 1 ? 0.3 : 0.16;
  if (r > threshold) return 0;
  return 1 + (hash(key + 7) % (month === 7 ? 3 : 2));
}

